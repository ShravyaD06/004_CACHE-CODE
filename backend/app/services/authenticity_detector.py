import os
import re
import math
from typing import Dict, Any, List, Optional
import pymupdf  # PyMuPDF 1.28.2
from PIL import Image

def calculate_text_burstiness_and_richness(text: str) -> Dict[str, Any]:
    """
    Computes linguistic burstiness (sentence length variance) and vocabulary
    richness (type-token ratio) to detect unnaturally uniform LLM-generated text.
    """
    if not text or len(text.strip()) < 30:
        return {
            "burstiness_score": 50.0,
            "vocabulary_richness": 50.0,
            "sentence_count": 0,
            "avg_sentence_len": 0,
            "is_suspiciously_uniform": False
        }

    # Split into sentences or major clauses
    sentences = [s.strip() for s in re.split(r'[.\n!?]+', text) if len(s.strip()) > 3]
    if len(sentences) < 3:
        return {
            "burstiness_score": 60.0,
            "vocabulary_richness": 60.0,
            "sentence_count": len(sentences),
            "avg_sentence_len": len(text) / max(len(sentences), 1),
            "is_suspiciously_uniform": False
        }

    lengths = [len(s.split()) for s in sentences]
    mean_len = sum(lengths) / len(lengths)
    variance = sum((l - mean_len) ** 2 for l in lengths) / len(lengths)
    std_dev = math.sqrt(variance)

    # Human business text (mixing short tables, headers, and body sentences) has high std_dev.
    # Formulaic LLM prompts without structure often have low std_dev relative to mean.
    cv = (std_dev / mean_len) if mean_len > 0 else 0
    burstiness_score = min(100.0, max(0.0, cv * 70.0))

    # Type-Token Ratio
    words = [w.lower() for w in re.findall(r'\b[a-zA-Z]{3,}\b', text)]
    total_words = len(words)
    unique_words = len(set(words))
    ttr = (unique_words / total_words) if total_words > 0 else 0.5
    richness_score = min(100.0, max(0.0, ttr * 100.0))

    is_uniform = cv < 0.25 and len(sentences) >= 5

    return {
        "burstiness_score": round(burstiness_score, 1),
        "vocabulary_richness": round(richness_score, 1),
        "sentence_count": len(sentences),
        "avg_sentence_len": round(mean_len, 1),
        "is_suspiciously_uniform": is_uniform
    }

def detect_synthetic_placeholders(text: str) -> List[str]:
    """
    Finds stereotypical placeholder companies, addresses, and dummy identities
    frequently generated by LLMs during synthetic document fabrication.
    """
    suspicious_patterns = [
        (r'\bacme\s+(?:corp|corporation|inc|industries|technologies)\b', "Acme Corporation archetype"),
        (r'\b(?:123\s+main\s+st|anytown|anycity|sample\s+street)\b', "Generic dummy address placeholder"),
        (r'\b(?:john\s+doe|jane\s+doe|test\s+user)\b', "Default placeholder entity name"),
        (r'\b(?:lorem\s+ipsum|consectetur\s+adipiscing)\b', "Lorem Ipsum dummy text"),
        (r'\b(?:sample\s+company|xyz\s+enterprises|example\s+corp)\b', "Synthetic placeholder company"),
        (r'\b(?:000-000-0000|123-456-7890|555-0199)\b', "Fictitious dummy phone number"),
        (r'\b(?:test@example\.com|user@domain\.com)\b', "RFC 2606 reserved example domain")
    ]
    detected = []
    text_lower = text.lower()
    for pattern, label in suspicious_patterns:
        if re.search(pattern, text_lower):
            detected.append(label)
    return detected

def analyze_pdf_metadata_provenance(filepath: str) -> Dict[str, Any]:
    """
    Inspects PDF header metadata and binary strings for synthetic compilers,
    headless browsers, or AI document generation engines.
    """
    result = {
        "is_pdf": False,
        "producer": "",
        "creator": "",
        "creation_date": "",
        "mod_date": "",
        "synthetic_compiler_detected": None,
        "enterprise_scanner_detected": None,
        "has_c2pa_provenance": False
    }

    if not os.path.exists(filepath):
        return result

    try:
        doc = pymupdf.open(filepath)
        result["is_pdf"] = True
        meta = doc.metadata or {}
        result["producer"] = meta.get("producer", "") or ""
        result["creator"] = meta.get("creator", "") or ""
        result["creation_date"] = meta.get("creationDate", "") or ""
        result["mod_date"] = meta.get("modDate", "") or ""
        doc.close()
    except Exception:
        pass

    # Read binary header/tail to inspect software signatures
    try:
        with open(filepath, "rb") as f:
            chunk = f.read(32768)  # first 32KB
            chunk_str = chunk.decode("latin-1", errors="ignore").lower()
            
            # C2PA manifest marker
            if "c2pa" in chunk_str or "c2ma" in chunk_str:
                result["has_c2pa_provenance"] = True

            # Synthetic / Programmatic compilers
            synthetic_keywords = [
                ("reportlab", "ReportLab Python PDF Engine"),
                ("weasyprint", "WeasyPrint Automated HTML2PDF"),
                ("wkhtmltopdf", "wkhtmltopdf Headless Engine"),
                ("puppeteer", "Google Puppeteer Headless Chrome"),
                ("playwright", "Playwright Synthetic Browser"),
                ("canva", "Canva Graphic Design Tool"),
                ("fpdf", "FPDF PHP Engine"),
                ("jspdf", "jsPDF Client Generator"),
                ("dompdf", "DOMPDF Engine"),
                ("pdfkit", "PDFKit Synthetic Generator")
            ]
            for kw, label in synthetic_keywords:
                if kw in result["producer"].lower() or kw in result["creator"].lower() or kw in chunk_str:
                    result["synthetic_compiler_detected"] = label
                    break

            # Hardware scanner signatures
            scanner_keywords = [
                ("canon", "Canon imageRUNNER / Scanner"),
                ("xerox", "Xerox WorkCentre / DocuColor"),
                ("hp ", "HP Digital Sender / ScanJet"),
                ("hewlett-packard", "HP Imaging Platform"),
                ("ricoh", "Ricoh Aficio Scanner"),
                ("epson", "Epson WorkForce Scanner"),
                ("brother", "Brother Scanner Engine"),
                ("fujitsu", "Fujitsu ScanSnap Hardware"),
                ("acrobat", "Adobe Acrobat Pro Standard")
            ]
            for kw, label in scanner_keywords:
                if kw in result["producer"].lower() or kw in result["creator"].lower() or kw in chunk_str:
                    result["enterprise_scanner_detected"] = label
                    break
    except Exception:
        pass

    return result

def analyze_image_exif_provenance(filepath: str) -> Dict[str, Any]:
    """
    Inspects image EXIF tags for smartphone / scanner camera hardware tags vs AI image generator signatures.
    """
    result = {
        "is_image": False,
        "has_exif": False,
        "camera_make": None,
        "camera_model": None,
        "software": None,
        "ai_generator_signature": None
    }

    try:
        with Image.open(filepath) as img:
            result["is_image"] = True
            exif_data = img.getexif()
            if exif_data and len(exif_data) > 0:
                result["has_exif"] = True
                # EXIF tag 271: Make, 272: Model, 305: Software
                result["camera_make"] = exif_data.get(271)
                result["camera_model"] = exif_data.get(272)
                result["software"] = exif_data.get(305)

            # Check png/jpeg text chunks for AI prompts
            info = img.info or {}
            info_str = str(info).lower()
            ai_tools = [
                ("stable diffusion", "Stable Diffusion / AUTOMATIC1111"),
                ("midjourney", "Midjourney Generation Platform"),
                ("dall-e", "OpenAI DALL-E"),
                ("novelai", "NovelAI Diffusion"),
                ("comfyui", "ComfyUI Node Generator"),
                ("flux", "Black Forest Labs Flux"),
                ("adobe firefly", "Adobe Firefly AI")
            ]
            for tool, label in ai_tools:
                if tool in info_str or (result["software"] and tool in str(result["software"]).lower()):
                    result["ai_generator_signature"] = label
                    break
    except Exception:
        pass

    return result

def detect_document_authenticity(
    filepath: str,
    ocr_data: Dict[str, Any],
    validated_fields: Optional[List[Dict[str, Any]]] = None,
    validation_issues: Optional[List[Dict[str, Any]]] = None
) -> Dict[str, Any]:
    """
    Comprehensive multi-layer forensic detection engine to determine whether an
    uploaded document is an authentic physical/scanned business document or
    an AI-generated / synthetic artifact.
    """
    signals = []
    authenticity_score = 95.0  # Default benchmark for standard document
    full_text = ocr_data.get("full_text", "")

    # Layer 1: PDF / Binary Provenance Inspection
    pdf_meta = analyze_pdf_metadata_provenance(filepath)
    if pdf_meta["synthetic_compiler_detected"]:
        signals.append({
            "id": "SYNTHETIC_PDF_COMPILER",
            "category": "metadata",
            "severity": "WARNING",
            "title": "Programmatic PDF Generator Detected",
            "description": f"Document binary contains signature of '{pdf_meta['synthetic_compiler_detected']}', indicating an automated script rather than a physical scanner or ERP print spool.",
            "evidence": pdf_meta["synthetic_compiler_detected"]
        })
        authenticity_score -= 25.0

    if pdf_meta["enterprise_scanner_detected"]:
        signals.append({
            "id": "AUTHENTIC_SCANNER_VERIFIED",
            "category": "metadata",
            "severity": "INFO",
            "title": "Enterprise Scanner Hardware Signature",
            "description": f"Document matches known hardware signature from {pdf_meta['enterprise_scanner_detected']}.",
            "evidence": pdf_meta["enterprise_scanner_detected"]
        })
        authenticity_score += 5.0

    # Layer 2: Image EXIF & Diffusion Generator Inspection
    img_meta = analyze_image_exif_provenance(filepath)
    if img_meta["ai_generator_signature"]:
        signals.append({
            "id": "AI_GENERATOR_SIGNATURE_FOUND",
            "category": "metadata",
            "severity": "CRITICAL",
            "title": "AI Image Generator Signature Detected",
            "description": f"Image metadata embeds signatures of '{img_meta['ai_generator_signature']}'.",
            "evidence": img_meta["ai_generator_signature"]
        })
        authenticity_score -= 50.0

    # Layer 3: Linguistic Analysis & Burstiness
    burst_metrics = calculate_text_burstiness_and_richness(full_text)
    if burst_metrics["is_suspiciously_uniform"]:
        signals.append({
            "id": "UNNATURAL_TEXT_BURSTINESS",
            "category": "linguistics",
            "severity": "WARNING",
            "title": "Unnaturally Uniform Sentence Cadence",
            "description": f"Sentence length standard deviation is extremely low (Burstiness Index: {burst_metrics['burstiness_score']}/100), characteristic of synthetic LLM paragraph generation.",
            "evidence": f"Burstiness: {burst_metrics['burstiness_score']}, Avg length: {burst_metrics['avg_sentence_len']} words"
        })
        authenticity_score -= 20.0

    # Synthetic Placeholders
    placeholders = detect_synthetic_placeholders(full_text)
    if placeholders:
        for p in placeholders[:2]:
            signals.append({
                "id": "SYNTHETIC_ENTITY_PLACEHOLDER",
                "category": "linguistics",
                "severity": "WARNING",
                "title": f"Common AI Dummy Placeholder: {p}",
                "description": "Document text contains formulaic placeholder entities commonly hallucinated by generative models.",
                "evidence": p
            })
            authenticity_score -= 15.0

    # Layer 4: Mathematical Sanity & Arithmetic Inconsistency
    if validation_issues:
        for issue in validation_issues:
            if issue.get("issue_type") == "ARITHMETIC_MISMATCH":
                signals.append({
                    "id": "ARITHMETIC_HALLUCINATION",
                    "category": "arithmetic",
                    "severity": "CRITICAL",
                    "title": "Cross-Field Arithmetic Discrepancy",
                    "description": "Subtotal, tax, and grand total fail mathematical cross-validation, a primary indicator of LLM hallucinations or manual forgery.",
                    "evidence": issue.get("message", "Subtotal + Tax != Total")
                })
                authenticity_score -= 30.0
                break

    # Clamp Authenticity Score between 5.0 and 99.0
    authenticity_score = max(5.0, min(99.0, round(authenticity_score, 1)))

    # Determine Risk Classification
    if authenticity_score >= 80.0:
        risk_level = "LOW"
        verdict = "Authentic Document (Low Risk of AI Generation)"
    elif authenticity_score >= 50.0:
        risk_level = "MEDIUM"
        verdict = "Suspicious Signals Detected (Review Provenance)"
    else:
        risk_level = "HIGH"
        verdict = "Likely AI-Generated or Synthetically Fabricated"

    return {
        "authenticity_score": authenticity_score,
        "risk_level": risk_level,
        "verdict": verdict,
        "signals": signals,
        "metadata_provenance": {
            "producer": pdf_meta.get("producer") or "Not Specified",
            "creator": pdf_meta.get("creator") or "Not Specified",
            "has_exif": img_meta.get("has_exif", False),
            "camera_model": img_meta.get("camera_model") or "None (Digital File)"
        },
        "linguistic_metrics": burst_metrics
    }
